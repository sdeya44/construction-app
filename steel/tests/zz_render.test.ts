import { it } from 'vitest';
import fs from 'node:fs';
import { defaultBuilding, newProject } from '../src/model/defaults';
import { defaultKneeBraces } from '../src/geometry/knee';
import { generate } from '../src/geometry/generate';
import { computeFabrication } from '../src/fab/marks';
import { computeBom } from '../src/fab/bom';
import { buildSheet, drawingCatalog } from '../src/drawing/views';
import { sheetToSvg } from '../src/drawing/svg';
import { numberParts } from '../src/commands/commands';
it('r', () => {
  const b = defaultBuilding(); const f = [...b.frames].sort((x, y) => x.y - y.y);
  b.kneeBraces = { ...defaultKneeBraces(), enabled: true };
  if (process.env.TB) b.transfers = [{ id: 'T1', lineId: 'L', from: f[1].id, to: f[4].id, removed: [f[2].id, f[3].id], profile: 'IPE600', support: 'A1', seat: 'B1' }];
  let p = newProject('x', b); p = numberParts().run(p);
  const d = generate(p); const fab = computeFabrication(p, d); const bom = computeBom(d, fab);
  const cat = drawingCatalog(p, d, fab);
  const only = (process.env.ONLY ?? '').split(',').filter(Boolean);
  console.log(cat.map(c => c.number + '=' + c.id).join(' '));
  for (const def of cat) if (only.some(o => def.id === o || def.number === o)) fs.writeFileSync('/tmp/claude-0/-home-user-construction-app/1a50a160-0b21-5222-a7ee-30b6297ca40e/scratchpad/rv2/' + def.number + '.svg', sheetToSvg(buildSheet(def, p, d, fab, bom)));
});
